const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('assert');
(async()=>{
  const executablePath=['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(fs.existsSync);
  const browser=await chromium.launch({headless:true,executablePath});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',error=>errors.push(String(error)));
  await page.goto('http://127.0.0.1:8785');
  await page.locator('#devices [data-host]').first().waitFor();
  assert.equal(await page.locator('#devices [data-host]').count(),6);
  await page.locator('[data-host="SINOV-PC-01"]').click();
  await page.locator('#detail-screen').waitFor();
  await page.screenshot({path:'build/dashboard-v4.png',fullPage:true});
  await page.locator('#detail-apps').click();
  await page.getByRole('button',{name:'Oynasi ochiq',exact:true}).click();
  assert.equal(await page.locator('.app-row').count(),1);
  await page.getByRole('button',{name:'Topilgan EXE’lar',exact:true}).click();
  assert.equal(await page.locator('.app-row').count(),20);
  await page.locator('#next').click();
  assert((await page.locator('#page-info').textContent()).includes('2 / 3'));
  await page.locator('#app-search').fill('sample-44');
  assert.equal(await page.locator('.app-row').count(),1);
  await page.getByRole('button',{name:'Bloklashga qo‘shish',exact:true}).click();
  assert.equal(await page.locator('#blocked-apps').inputValue(),'sample-44.exe');
  await page.locator('#save').click();
  await page.locator('#message').filter({hasText:'Saqlandi'}).waitFor();
  await page.locator('[data-page="overview"]').click();
  await page.locator('#detail-screen').click();
  await page.locator('#remote-screen').waitFor({state:'visible',timeout:15000});
  await page.screenshot({path:'build/viewer-v4.png',fullPage:true});
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'))});
  await page.waitForTimeout(3300);
  const stopped=await page.evaluate(async()=>{const s=await (await fetch('/api/state')).json();return s.desktop['SINOV-PC-01'].mode});
  assert.equal(stopped,'idle','A hidden tab must not renew screen capture');
  await page.evaluate(()=>{delete document.hidden});
  await page.locator('#stop-viewer').click();
  await page.locator('[data-page="screens"]').click();
  await page.locator('.screen-card img').first().waitFor({state:'visible'});
  await page.screenshot({path:'build/screens-v4.png',fullPage:true});
  await page.locator('#stop-wall').click();
  await page.locator('[data-page="settings"]').click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'build/mobile-v4.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
  assert.deepEqual(errors,[]);
  await browser.close();console.log('UI flows OK: selection, open windows, pagination, block/save, live viewer, screen wall, mobile.');
})().catch(error=>{console.error(error);process.exit(1)});
